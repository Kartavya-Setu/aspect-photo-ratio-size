const fs = require('fs');
const path = require('path');

// Read .env file from project root if present
const envPath = path.resolve(__dirname, '../.env');
const envVars = {};

if (fs.existsSync(envPath)) {
  const fileContent = fs.readFileSync(envPath, 'utf8');
  fileContent.split(/\r?\n/).forEach(line => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) return;
    const match = trimmed.match(/^([^=]+)=(.*)$/);
    if (match) {
      const key = match[1].trim();
      let val = match[2].trim();
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }
      envVars[key] = val;
    }
  });
}

// Fallback to system environment variables (useful for CI/CD and deployment platforms)
const apiKey = envVars.GEMINI_API_KEY || process.env.GEMINI_API_KEY || '';
const model = envVars.GEMINI_MODEL || process.env.GEMINI_MODEL || 'gemini-3.5-flash-lite';

const targetDir = path.resolve(__dirname, '../src/environments');
if (!fs.existsSync(targetDir)) {
  fs.mkdirSync(targetDir, { recursive: true });
}

const devEnvironmentContent = `// Auto-generated by scripts/set-env.js - DO NOT COMMIT THIS FILE
export const environment = {
  production: false,
  geminiApiKey: '${apiKey}',
  geminiModel: '${model}'
};
`;

const prodEnvironmentContent = `// Auto-generated by scripts/set-env.js - DO NOT COMMIT THIS FILE
export const environment = {
  production: true,
  geminiApiKey: '${apiKey}',
  geminiModel: '${model}'
};
`;

fs.writeFileSync(path.join(targetDir, 'environment.ts'), devEnvironmentContent, 'utf8');
fs.writeFileSync(path.join(targetDir, 'environment.prod.ts'), prodEnvironmentContent, 'utf8');

const maskedKey = apiKey
  ? `${apiKey.substring(0, 6)}...${apiKey.substring(apiKey.length - 4)}`
  : '(none configured - offline heuristic mode active)';

console.log(`[set-env] Generated Angular environment files.`);
console.log(`[set-env] Gemini API Key: ${maskedKey}`);
